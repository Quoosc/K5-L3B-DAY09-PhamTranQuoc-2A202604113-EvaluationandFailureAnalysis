"""Capture exact submission evidence from commands, including expected exit codes.

Run from src: python -m lab9.submission_check
No baseline/report values are edited by this script.
"""
import subprocess
import sys
from pathlib import Path

def main():
    checks = [
        ('-m lab9.smoke', 0),
        ('-m pytest -q -o addopts=', 0),
        ('-m lab9.evalset --check', 0),
        ('-m lab9.evalset --v2', 0),
        ('-m lab9.final_review', 0),
        ('-m lab9.eval --shape swarm --out reports/eval_pr.json', 0),
        ('-m lab9.ci_check --pr reports/eval_pr.json --baseline reports/baseline_v1.json', 0),
        ('-m lab9.gate --pr reports/eval_pr.json --baseline reports/baseline_v1.json', 0),
        ('-m lab9.gate --pr reports/eval_fixed.json --baseline reports/baseline_v1.json', 0),
        ('-m lab9.gate --pr reports/eval_seeded_regression.json --baseline reports/baseline_v1.json', 1),
        ('-m lab9.mutation --detect', 0),
        ('-m lab9.mutation --spec config/metric_spec_v2.yaml --baseline reports/baseline_v2.json', 0),
        ('-m lab9.mutation --spec config/metric_spec_v2.yaml --aa 66,77,88,99,110', 0),
        ('-m lab9.traps --pr reports/eval_slice_regression.json --baseline reports/baseline_v2.json --spec config/metric_spec_v2.yaml', 0),
    ]
    for name in ['evaluator_errors_as_nan', 'dropped_failing_rows', 'cherry_picked_seeds', 'loosened_spec']:
        cmd = f'-m lab9.gate --pr reports/traps/{name}.json --baseline reports/baseline_v2.json --spec config/metric_spec_v2.yaml'
        if name == 'loosened_spec':
            cmd = cmd.replace('--spec config/metric_spec_v2.yaml', '--spec reports/traps/loosened_spec.spec.yaml --base-spec config/metric_spec_v2.yaml')
        checks.append((cmd, 1))
    chunks = ['# Exact submission command outputs\n\nGenerated by `python -m lab9.submission_check`.\n']
    for cmd, expected in checks:
        result = subprocess.run([sys.executable, *cmd.split()], capture_output=True, text=True, encoding='utf8')
        output = result.stdout + result.stderr
        chunks.append(f'\n## python {cmd}\n\n```text\n{output}\nprocess exit {result.returncode}; expected {expected}\n```\n')
        print(f'{cmd}: exit {result.returncode} (expected {expected})', flush=True)
        if result.returncode != expected:
            Path('reports/submission_evidence.md').write_text(''.join(chunks), encoding='utf8')
            raise RuntimeError(output)
    Path('reports/submission_evidence.md').write_text(''.join(chunks), encoding='utf8')
    print('All submission checks passed; exact evidence saved.', flush=True)

if __name__ == '__main__':
    main()
